// Get weather icon based on OWM weather ID
const uint8_t* getWeatherIcon32(int16_t weatherId, const char* iconCode) {
  if (weatherId >= 200 && weatherId < 300) return icon_thunder_32;   // Thunderstorm
  if (weatherId >= 300 && weatherId < 400) return icon_rain_32;      // Drizzle
  if (weatherId >= 500 && weatherId < 600) return icon_rain_32;      // Rain
  if (weatherId >= 600 && weatherId < 700) return icon_snow_32;      // Snow
  if (weatherId >= 700 && weatherId < 800) return icon_mist_32;      // Atmosphere
  if (weatherId == 800)                    return icon_sun_32;        // Clear
  if (weatherId > 800)                     return icon_cloud_32;      // Clouds
  return icon_cloud_32;
}
